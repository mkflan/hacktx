"""Prompt tab and catalog personalization. Stateless: nothing is saved (persisted=false)."""

from collections.abc import Callable

from ..api.schemas import (
    ElaborateIdeaRequest,
    GenerateIdeasRequest,
    Notice,
    PersonalizationPreferences,
    PersonalizeRequest,
)
from ..contracts import NormalizedUser, Resource
from ..dependencies import AppContext
from ..errors import AppError, not_found
from ..llm.prompting import prompt_version
from ..llm.schemas import ProjectPlan, ProjectPlanDraft
from ..llm.validation import plan_constraint_notices, validate_ideas, validate_plan
from .cache import content_key
from .resources import build_resource_bank, default_search_queries, hydrate


def _load_user(ctx: AppContext, user_id: str) -> NormalizedUser:
    user = ctx.data.get_user(user_id)
    if user is None:
        raise not_found("user", user_id)
    return user


def _common_notices(
    ctx: AppContext, prefs: PersonalizationPreferences | None, bank: list[Resource]
) -> list[Notice]:
    notices: list[Notice] = []
    if ctx.llm.mode == "mock":
        notices.append(
            Notice(
                code="MOCK_GENERATION",
                message="Generated by the offline mock provider, not a real model.",
            )
        )
    if not prefs or prefs.skill_level is None:
        notices.append(
            Notice(
                code="SKILL_LEVEL_UNKNOWN",
                message="No skill level was given; see each item's assumptions.",
            )
        )
    if not bank:
        notices.append(
            Notice(
                code="NO_RESOURCES",
                message="No supplied guides or research matched; see suggested_search_queries "
                "(suggestions only, not checked sources).",
            )
        )
    elif any(r.verification_status == "provided_unverified" for r in bank):
        notices.append(
            Notice(
                code="RESOURCES_UNVERIFIED",
                message="Linked resources were supplied by the catalog and have not been verified.",
            )
        )
    return notices


def _cached(ctx: AppContext, key_parts: dict, produce: Callable[[], dict]) -> dict:
    llm = ctx.llm
    key = content_key(
        **key_parts,
        prompt_version=prompt_version(),
        model=llm.model_id,
        llm_mode=llm.mode,
        data_source=ctx.data_source,
    )
    hit = ctx.cache.get(key)
    if hit is not None:
        hit["cache_hit"] = True
        return hit
    body = produce()
    ctx.cache.set(key, body)
    return {**body, "cache_hit": False}


def _bank_dump(bank: list[Resource]) -> list[dict]:
    return [r.model_dump(mode="json") for r in bank]


def _prefs_dump(prefs: PersonalizationPreferences | None) -> dict | None:
    return prefs.model_dump(mode="json") if prefs else None


def _plan_from_draft(
    draft: ProjectPlanDraft,
    bank: list[Resource],
    user: NormalizedUser,
    prefs: PersonalizationPreferences | None,
    focus: str,
) -> tuple[ProjectPlan, list[Notice]]:
    errors = validate_plan(draft, bank, user)
    if errors:
        raise AppError(
            "LLM_INVALID_OUTPUT",
            "The generated plan failed validation.",
            502,
            retryable=True,
            details=[{"msg": e} for e in errors[:10]],
        )
    referenced = [*draft.resource_ids]
    for milestone in draft.milestones:
        referenced += milestone.resource_ids
    research = hydrate(draft.research_resource_ids, bank)
    examples = hydrate(draft.example_resource_ids, bank)
    body = draft.model_dump(
        exclude={"resource_ids", "research_resource_ids", "example_resource_ids"}
    )
    if not body["suggested_search_queries"] and not (research and examples):
        body["suggested_search_queries"] = default_search_queries(focus, user.interests)
    plan = ProjectPlan(
        **body,
        resources=hydrate(referenced, bank),
        research_connections=research,
        similar_examples=examples,
    )
    notices = plan_constraint_notices(draft, user, prefs)
    if not research:
        notices.append(
            Notice(
                code="NO_RESEARCH_SOURCES",
                message="No supplied research matched this plan; research_connections is empty.",
            )
        )
    return plan, notices


def generate_ideas(ctx: AppContext, user_id: str, req: GenerateIdeasRequest) -> dict:
    user = _load_user(ctx, user_id)
    projects = ctx.data.list_projects()
    bank = build_resource_bank(projects, [req.topic or "", *user.interests])
    llm = ctx.llm

    def produce() -> dict:
        draft = llm.generate_ideas(user, req.preferences, req.topic, bank, req.limit)
        errors = validate_ideas(draft)
        if errors:
            raise AppError(
                "LLM_INVALID_OUTPUT",
                "Generated ideas failed validation.",
                502,
                retryable=True,
                details=[{"msg": e} for e in errors],
            )
        return {
            "mode": "generate_ideas",
            "user_id": user.id,
            "ideas": [i.model_dump(mode="json") for i in draft.ideas[: req.limit]],
            "generation_mode": llm.mode,
            "data_source": ctx.data_source,
            "persisted": False,
            "warnings": [n.model_dump() for n in _common_notices(ctx, req.preferences, bank)],
        }

    key = {
        "action": "generate_ideas",
        "user": user.model_dump(mode="json"),
        "preferences": _prefs_dump(req.preferences),
        "topic": req.topic,
        "limit": req.limit,
        "bank": _bank_dump(bank),
    }
    return _cached(ctx, key, produce)


def elaborate_idea(
    ctx: AppContext,
    user_id: str,
    req: ElaborateIdeaRequest,
    extra_resources: list[Resource] = (),
) -> dict:
    """extra_resources (for example live web results found for the idea) go first in the bank
    and are the only way a plan can cite something outside the catalog."""
    user = _load_user(ctx, user_id)
    projects = ctx.data.list_projects()
    extra_ids = {r.id for r in extra_resources}
    bank = list(extra_resources) + [
        r for r in build_resource_bank(projects, [req.idea]) if r.id not in extra_ids
    ]
    llm = ctx.llm

    def produce() -> dict:
        draft = llm.elaborate_idea(user, req.preferences, req.idea, bank)
        plan, notices = _plan_from_draft(draft, bank, user, req.preferences, req.idea)
        return {
            "mode": "elaborate_idea",
            "user_id": user.id,
            "original_idea": req.idea,
            "project": plan.model_dump(mode="json"),
            "generation_mode": llm.mode,
            "data_source": ctx.data_source,
            "persisted": False,
            "warnings": [
                n.model_dump() for n in _common_notices(ctx, req.preferences, bank) + notices
            ],
        }

    key = {
        "action": "elaborate_idea",
        "user": user.model_dump(mode="json"),
        "preferences": _prefs_dump(req.preferences),
        "idea": req.idea,
        "bank": _bank_dump(bank),
    }
    return _cached(ctx, key, produce)


def personalize_project(
    ctx: AppContext, user_id: str, project_id: str, req: PersonalizeRequest
) -> dict:
    user = _load_user(ctx, user_id)
    project = ctx.data.get_project(project_id)
    if project is None:
        raise not_found("project", project_id)
    projects = ctx.data.list_projects()
    bank = build_resource_bank(projects, [project.name, *project.interests], primary=project)
    llm = ctx.llm

    def produce() -> dict:
        draft = llm.personalize_project(user, req.preferences, project, bank)
        plan, notices = _plan_from_draft(draft, bank, user, req.preferences, project.name)
        return {
            "user_id": user.id,
            "source_project_id": project.id,
            "project": plan.model_dump(mode="json"),
            "generation_mode": llm.mode,
            "data_source": ctx.data_source,
            "persisted": False,
            "warnings": [
                n.model_dump() for n in _common_notices(ctx, req.preferences, bank) + notices
            ],
        }

    key = {
        "action": "personalize_project",
        "user": user.model_dump(mode="json"),
        "preferences": _prefs_dump(req.preferences),
        "project": project.model_dump(mode="json"),
        "bank": _bank_dump(bank),
    }
    return _cached(ctx, key, produce)
